import {useEffect,useState} from 'react';
import AppShell from './app/AppShell';
import PageBoundary from './app/PageBoundary';
import {parseLocation,subscribeRoute,navigate} from './app/router';
import {pages} from './app/navigation';
import {ConnectionsPage,DiagnosticsPage,OverviewPage,useCapabilities} from './app/LivePages';
import MarketDashboard from './market/MarketDashboard';
import Account from './account/Account';
import SpotPaper from './paper/SpotPaper';
import Recommend from './recommend/Recommend';
import Research from './research/Research';
export default function App(){const[location,setLocation]=useState(()=>parseLocation(new URL(window.location.href)));useEffect(()=>subscribeRoute(()=>setLocation(parseLocation(new URL(window.location.href)))),[]);const route={...location,demo:import.meta.env.DEV&&location.demo};useEffect(()=>{document.title=pages[route.page].title+' · 매매 대시보드'},[route.page]);const cap=useCapabilities(!route.demo&&['paper','run','create','backtest'].includes(route.page));let content;
 if(route.page==='overview')content=<OverviewPage route={route}/>;
 else if(route.page==='connections')content=<ConnectionsPage demo={route.demo}/>;
 else if(route.page==='diagnostics')content=<DiagnosticsPage route={route}/>;
 else if(route.page==='market')content=<MarketDashboard demo={route.demo} polished/>;
 else if(route.page==='account')content=<Account demo={route.demo} polished/>;
 else if(route.page==='paper')content=<SpotPaper key={'spot:'+route.demo} demo={route.demo} capabilities={cap.data}/>;
 else if(route.page==='recommend')content=<Recommend key={'recommend:'+route.demo} demo={route.demo} polished/>;
 else content=<Research key={route.page+route.id+route.demo} demo={route.demo} polished page={route.page} selectedId={route.id} capabilities={cap.data} onOpenRun={id=>navigate({...route,page:'run',id})}/>;
 return <AppShell route={route}><PageBoundary key={route.page+':'+route.demo+':'+route.id}>{content}</PageBoundary></AppShell>}
